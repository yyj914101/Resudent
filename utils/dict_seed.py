from models import db, DictCategory, DictItem

CARE_SUPPORT_CATEGORIES = {
    '供养方式': ['集中供养', '分散供养', '亲属供养', '其他'],
    '供养机构': ['镇敬老院', '县福利院', '村级照料中心', '其他'],
}


def seed_pair(item):
    """种子条目归一：'标签' → (标签, 标签)；(标签, 值) 元组原样展开（090A D-01 value 编码形态）。"""
    if isinstance(item, str):
        return item, item
    label, value = item
    return label, value


def seed_label(item):
    """种子条目取展示标签（dict_enum.get_enum 回退用，元组形态取首元素）。"""
    return item if isinstance(item, str) else item[0]


def _ensure_category(name, labels, sort_order):
    """补齐单个分类：返回本分类新增项数。"""
    cat = DictCategory.query.filter_by(name=name).first()
    if not cat:
        cat = DictCategory(name=name, description=name, sort_order=sort_order)
        db.session.add(cat)
        db.session.flush()
    existing = {row.label for row in DictItem.query.filter_by(category_id=cat.id).all()}
    added = 0
    for idx, item in enumerate(labels):
        label, value = seed_pair(item)
        if label in existing:
            continue
        db.session.add(DictItem(category_id=cat.id, label=label, value=value, sort_order=idx))
        added += 1
    return added


def ensure_care_support_dict():
    """补录「供养方式 / 供养机构」两分类及缺项。返回 (新建分类数, 新增项数)；幂等可重跑。"""
    max_sort = db.session.query(db.func.max(DictCategory.sort_order)).scalar() or 0
    new_cats = 0
    new_items = 0
    for name, labels in CARE_SUPPORT_CATEGORIES.items():
        existed = DictCategory.query.filter_by(name=name).first() is not None
        added = _ensure_category(name, labels, max_sort + 10)
        if not existed:
            new_cats += 1
            max_sort += 10
        new_items += added
    db.session.commit()
    return new_cats, new_items


